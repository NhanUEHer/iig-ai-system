const express=require('express');const asyncHandler=require('../http/asyncHandler');const {requirePermission}=require('../middleware/authenticate');const c=require('../controllers/examV3Controller');const r=express.Router();
r.get('/',requirePermission('exams.view'),asyncHandler(c.list));
r.post('/',requirePermission('exams.manage'),asyncHandler(c.create));
r.get('/:examId/available-questions',requirePermission('exams.view'),asyncHandler(c.available));
r.get('/:examId/validation',requirePermission('exams.view'),asyncHandler(c.validation));
r.post('/:examId/activate',requirePermission('exams.manage'),asyncHandler(c.activate));
r.post('/:examId/deactivate',requirePermission('exams.manage'),asyncHandler(c.deactivate));
r.post('/:examId/duplicate',requirePermission('exams.manage'),asyncHandler(c.duplicate));
r.post('/:examId/parts',requirePermission('exams.manage'),asyncHandler(c.addPart));
r.put('/:examId/parts/reorder',requirePermission('exams.manage'),asyncHandler(c.reorderParts));
r.put('/:examId/parts/:partId',requirePermission('exams.manage'),asyncHandler(c.updatePart));
r.delete('/:examId/parts/:partId',requirePermission('exams.manage'),asyncHandler(c.removePart));
r.post('/:examId/parts/:partId/questions',requirePermission('exams.manage'),asyncHandler(c.addQuestions));
r.put('/:examId/parts/:partId/questions/reorder',requirePermission('exams.manage'),asyncHandler(c.reorderQuestions));
r.delete('/:examId/parts/:partId/questions/:questionId',requirePermission('exams.manage'),asyncHandler(c.removeQuestion));
r.get('/:examId',requirePermission('exams.view'),asyncHandler(c.detail));
r.put('/:examId',requirePermission('exams.manage'),asyncHandler(c.update));
r.delete('/:examId',requirePermission('exams.manage'),asyncHandler(c.remove));
module.exports=r;
